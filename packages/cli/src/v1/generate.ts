export function stableStringify8(value: unknown): string {
  const sort = (v: unknown): unknown =>
    Array.isArray(v) ? v.map(sort) : typeof v === "object" && v !== null ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sort((v as Record<string, unknown>)[k])])) : v;
  return `${JSON.stringify(sort(value), null, 2)}\n`;
}
export const specHash8 = (ir: Ir8) => `sha256:${createHash("sha256").update(stableStringify8(ir)).digest("hex")}`;
const header = (ir: Ir8) => `// Code generated by clp. DO NOT EDIT.\n// ir-version: ${ir.irVersion}\n// spec-hash:  ${specHash8(ir)}\n`;
const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

// --- text-plan (Stage 0): how the contract is written ---

/** One type, with what is inside it already written. */
export type TypeFacts8 = {
  kind: "int" | "string" | "bool" | "json" | "enum" | "atom" | "optional" | "list" | "set" | "map" | "record";
  /** The sort of an atom. */
  name: string;
  /** What is inside (optional, list, set; a map's value), written. */
  inner: string;
  /** A map's key, written. */
  key: string;
  /** A record's fields, written; plain: the name is a plain identifier (otherwise it is quoted). */
  entries: { name: string; text: string; plain: boolean }[];
  /** An enumeration's members, written as constants. */
  members: string[];
};
export function typeText8Stage0(facts: TypeFacts8): string {
  const wrap = (text: string) => (/[|&]/.test(text) && !text.startsWith("{") ? `(${text})` : text);
  switch (facts.kind) {
    case "int":
      return "number";
    case "string":
      return "string";
    case "bool":
      return "boolean";
    case "json":
      return "Json";
    case "enum":
      return facts.members.join(" | ") || "never";
    case "atom":
      return facts.name;
    case "optional":
      return `${facts.inner} | null`;
    case "list":
    case "set":
      return `${wrap(facts.inner)}[]`;
    case "map":
      return `{ key: ${facts.key}; value: ${facts.inner} }[]`;
    case "record":
      return facts.entries.length === 0 ? "Record<string, never>" : `{ ${facts.entries.map((e) => `${e.plain ? e.name : JSON.stringify(e.name)}: ${e.text}`).join("; ")} }`;
  }
}
export type NotesFacts8 = { promise: "none" | "fresh" | "increasing"; mayFail: boolean };
export type NoteId8 = "fresh" | "increasing" | "may-fail";
export const notes8Stage0 = ({ promise, mayFail }: NotesFacts8): NoteId8[] => [...(promise === "none" ? [] : [promise]), ...(mayFail ? (["may-fail"] as const) : [])];
export type SectionFacts8 = { answering: number; queries: number; routes: number; restarts: boolean; sorts: number; json: boolean };
export type Sections8 = { commandOutput: boolean; queries: boolean; routes: boolean; restarts: boolean; sorts: boolean; json: boolean };
export const sections8Stage0 = (f: SectionFacts8): Sections8 => ({ commandOutput: f.answering > 0, queries: f.queries > 0, routes: f.routes > 0, restarts: f.restarts, sorts: f.sorts > 0, json: f.json });

/** Text decisions made beforehand by text-plan (Stage 1), keyed by the facts; without one, Stage 0 decides. */
export type Plan8 = { types: Map<string, string>; notes: Map<string, NoteId8[]>; sections: Map<string, Sections8> };
const PLANS = new Map<string, Plan8>();
export const registerPlan8 = (ir: Ir8, plan: Plan8) => void PLANS.set(specHash8(ir), plan);
let plan: Plan8 | undefined;

export function typeFacts8(t: Type, text: (inner: Type) => string): TypeFacts8 {
  const facts: TypeFacts8 = { kind: "int", name: "", inner: "", key: "", entries: [], members: [] };
  if (t === "int" || t === "string" || t === "bool" || t === "json") return { ...facts, kind: t };
  if ("enum" in t) return { ...facts, kind: "enum", members: t.enum.map((v) => JSON.stringify(v)) };
  if ("atom" in t) return { ...facts, kind: "atom", name: t.atom };
  if ("optional" in t) return { ...facts, kind: "optional", inner: text(t.optional) };
  if ("list" in t) return { ...facts, kind: "list", inner: text(t.list) };
  if ("set" in t) return { ...facts, kind: "set", inner: text(t.set) };
  if ("map" in t) return { ...facts, kind: "map", key: text(t.map[0]), inner: text(t.map[1]) };
  return { ...facts, kind: "record", entries: Object.entries(t.record).map(([name, inner]) => ({ name, text: text(inner), plain: /^[A-Za-z_$][\w$]*$/.test(name) })) };
}
/** How a type is written in the contract. */
export function typeText(t: Type): string {
  const facts = typeFacts8(t, typeText);
  return plan?.types.get(JSON.stringify(facts)) ?? typeText8Stage0(facts);
}
const noteIds = (facts: NotesFacts8) => plan?.notes.get(JSON.stringify(facts)) ?? notes8Stage0(facts);
const sectionsOf = (facts: SectionFacts8) => plan?.sections.get(JSON.stringify(facts)) ?? sections8Stage0(facts);

/** Every fact the contract of an IR is written from (for text-plan to decide beforehand). */
export function contractFacts8(ir: Ir8): { types: TypeFacts8[]; notes: NotesFacts8[]; sections: SectionFacts8 } {
  const types: TypeFacts8[] = [];
  const walk = (t: Type): string => {
    const facts = typeFacts8(t, walk);
    types.push(facts);
    return typeText8Stage0(facts);
  };
  const entries = entriesOf(ir);
  for (const e of entries) {
    walk({ record: e.params });
    if (e.output) walk(e.output);
  }
  const notes: NotesFacts8[] = [];
  for (const c of Object.values(ir.components)) {
    for (const q of Object.values(c.external?.queries ?? {})) {
      walk({ record: q.params });
      walk(q.result);
      notes.push({ promise: q.promise ?? "none", mayFail: q.mayFail === true });
    }
    for (const command of Object.values(c.external?.commands ?? {})) walk({ record: command.params });
  }
  return { types, notes, sections: sectionFacts(ir) };
}
const sectionFacts = (ir: Ir8): SectionFacts8 => {
  const entries = entriesOf(ir);
  return {
    answering: entries.filter((e) => e.kind === "command" && e.output !== undefined).length,
    queries: entries.filter((e) => e.kind === "query").length,
    routes: Object.keys(ir.components[ir.root].routes ?? {}).length,
    restarts: restarts8(ir),
    sorts: ir.sorts.length,
    json: usesJson(ir),
  };
};
const usesJson = (ir: Ir8) => JSON.stringify(ir.components).includes('"json"');
const fieldsOf = (params: Record<string, Type>) => typeText({ record: params }).replace("Record<string, never>", "{}");

export const restarts8 = (ir: Ir8) => Object.values(ir.components).some((c) => c.durable);

export function contract8(ir: Ir8): string {
  plan = PLANS.get(specHash8(ir));
  try {
    return writeContract8(ir);
  } finally {
    plan = undefined;
  }
}
function writeContract8(ir: Ir8): string {
  const entries = entriesOf(ir);
  const sections = sectionsOf(sectionFacts(ir));
  const commands = entries.filter((e) => e.kind === "command");
  const queries = entries.filter((e) => e.kind === "query");
  const answering = commands.filter((e) => e.output !== undefined);
  const outside = Object.entries(ir.components).filter(([, c]) => c.external).sort(([a], [b]) => (a < b ? -1 : 1));
  const routes = sections.routes ? ir.components[ir.root].routes : undefined;
  const lines: string[] = [header(ir)];
  if (sections.sorts) {
    lines.push(`/** Identifiers: opaque values, compared only for equality. The harness makes them up; never parse them. */`);
    for (const sort of ir.sorts) lines.push(`export type ${sort} = string;`);
    lines.push("");
  }
  if (sections.json) lines.push("/** Any JSON value, carried as it is. */\nexport type Json = null | boolean | number | string | Json[] | { [key: string]: Json };\n");
  lines.push(
    `/**\n * Collections in inputs and answers: a set is an array in any order (no duplicates), a map is an array of\n * \`{ key, value }\` in any order (each key once). Lists are arrays in their order.\n */`,
    `/** One command to execute: its name and its input. A command changes the system; what it answers is compared with the specification. */`,
    `export type Command =\n${commands.map((e) => `  | { name: ${JSON.stringify(entryName(ir, e.qualified))}; input: ${fieldsOf(e.params)} }`).join("\n") || "  never"};\n`,
  );
  if (sections.commandOutput) {
    lines.push(
      `/** What each command answers with. Return it from \`executeCommand\`. Commands not listed here answer nothing. */`,
      `export type CommandOutput = {\n${answering.map((e) => `  ${key(entryName(ir, e.qualified))}: ${typeText(e.output!)};`).join("\n")}\n};\n`,
    );
  }
  if (sections.queries) {
    lines.push(
      `/** One query: it asks the system about what it holds now and changes nothing. */`,
      `export type Query =\n${queries.map((e) => `  | { name: ${JSON.stringify(entryName(ir, e.qualified))}; input: ${fieldsOf(e.params)} }`).join("\n")};\n`,
      `/** What each query answers with. Return it from \`executeQuery\`. */`,
      `export type QueryOutput = {\n${queries.map((e) => `  ${key(entryName(ir, e.qualified))}: ${typeText(e.output!)};`).join("\n")}\n};\n`,
    );
  }
  if (routes) {
    lines.push(
      `/**
 * The commands below reach the production system as HTTP requests. Start its server in \`setupIsolation\`
 * (on a free port) and send each command to its route:
 * - the method and the path are the route; a path segment \`:name\` is the input field \`name\` (URL-encoded);
 * - the input field \`body\` is the JSON request body; every other input field goes into the query string;
 * - the answer has the fields the command's output declares: \`status\` is the response status code, and
 *   \`body\` the response body parsed as JSON (\`null\` when the response has no body).
 */
export const routes = {
${Object.keys(routes).sort().map((name) => `  ${key(name)}: ${JSON.stringify(routes[name])},`).join("\n")}
} as const;
`,
    );
  }
  const portLines: string[] = [];
  for (const [id, c] of outside) {
    const members: string[] = [];
    for (const [name, port] of Object.entries(c.external!.queries).sort(([a], [b]) => (a < b ? -1 : 1))) {
      const notes = noteIds({ promise: port.promise ?? "none", mayFail: port.mayFail === true }).map((id) => NOTES8[id]);
      const params = Object.keys(port.params).length ? `input: ${fieldsOf(port.params)}` : "";
      members.push(`${notes.length ? `/** ${notes.join(" ")} */ ` : ""}${key(name)}(${params}): ${typeText(port.result)};`);
    }
    for (const [name, command] of Object.entries(c.external!.commands).sort(([a], [b]) => (a < b ? -1 : 1))) {
      members.push(`${key(name)}(input: ${fieldsOf(command.params)}): void;`);
    }
    portLines.push(`  ${key(id)}: {\n${members.map((m) => `    ${m}`).join("\n")}\n  };`);
  }
  if (sections.restarts) {
    portLines.push(
      `  /**\n   * Where the system keeps what must survive a restart: the path of a file that does not exist yet (a new one\n   * for every trial, removed afterwards). Give it to the production code as its storage location.\n   */\n  storage: string;`,
    );
  }
  lines.push(
    `/**
 * Stand-ins for the outside world the system depends on. The test harness owns them; connect them to whatever
 * seams your production code has. A query's answers can differ from one command to the next: ask when needed,
 * do not cache. A command on the outside world is recorded, in order, and compared with the specification.
 */
export type Ports = {
${portLines.join("\n")}
};
`,
  );
  lines.push(
    `/** The test harness drives the production system only through this interface. */
export interface TargetSystemAdapter {
  /** Called before each trial. Build a fresh system in its initial state, connected to \`ports\`. */
  setupIsolation(ports: Ports): Promise<void>;
  /** Called after each trial, pass or fail. Discard everything the trial created. */
  teardownIsolation(): Promise<void>;
  /** Execute one command. A trial executes several commands and queries in sequence on the same system. */
  executeCommand(command: Command): Promise<${sections.commandOutput ? "CommandOutput[keyof CommandOutput] | void" : "void"}>;${
    sections.queries
      ? `
  /** Answer one query. */
  executeQuery(query: Query): Promise<QueryOutput[keyof QueryOutput]>;`
      : ""
  }${
    sections.restarts
      ? `
  /**
   * Stop the production system and start it again on the same \`ports.storage\`, as after a crash or a
   * redeployment: a new instance, nothing carried over in memory. What it keeps must come back from storage.
   */
  restartSystem(): Promise<void>;`
      : ""
  }
}
`,
  );
  return lines.join("\n");
}

const NOTES8 = {
  fresh: "Never answers with the same value twice.",
  increasing: "Never answers with less than it answered before.",
  "may-fail": "May fail: throws when the dependency is unavailable. Let the exception reach the production code.",
} as const;

export const ADAPTER_NOT_WRITTEN = "the adapter is not written yet";

export function adapterSkeleton8(ws: Workspace, ir: Ir8): string {
  const methods = [
    "setupIsolation(ports)",
    "teardownIsolation()",
    "executeCommand(command)",
    ...(ir.entries.queries.length ? ["executeQuery(query)"] : []),
    ...(restarts8(ir) ? ["restartSystem()"] : []),
  ];
  return `import type { TargetSystemAdapter } from "${importPath(ws.paths.adapter, ws.paths.contract)}";

// Import the production code from ${dirFrom(ws.paths.adapter, ws.src)} and forward each call to it. No business logic here.
export const adapter: TargetSystemAdapter = {
${methods.map((method) => `  async ${method} {\n    throw new Error("${ADAPTER_NOT_WRITTEN}");\n  },`).join("\n")}
};
`;
}

export function verify8(ir: Ir8, ws: Workspace, specsDir: string): string {
  const specs = relative(testsDirOf(ws), specsDir).split(sep).join("/");
  return `${header(ir)}
import { fileURLToPath } from "node:url";
import { runPbt } from "@clp/cli/v1/runtime";
import { adapter } from "./${posix.basename(ws.paths.adapter)}";

await runPbt({ specs: fileURLToPath(new URL(${JSON.stringify(specs + "/")}, import.meta.url)), component: ${JSON.stringify(ws.component)}, adapter });
`;
}

// --- The spec view: the IR read aloud ---

/** The IR as an implementer reads it: every component, event, query and property, its expression read in English, and the notes next to it. */
export function specView(ir: Ir8, language: "ja" | "en" = "en"): string {
  const r = (e: unknown) => readOut(e, language);
  const note = (path: string) => (ir.notes?.[path] ? ` — “${ir.notes[path]}”` : "");
  const out: string[] = [];
  const t = language === "en";
  out.push(t ? `# Specification of \`${ir.root}\` (read from the IR)` : `# ${ir.root} の仕様（IR の読み下し）`, "");
  out.push(
    t
      ? "Every expression below is the IR's own expression read aloud; the IR (`*.ir.json`) is the precise form. Quoted text is the author's prose, for intent only."
      : "式は IR の式を機械的に読み下したもの。「」は書き手の文（意図の説明で、意味には使わない）。",
    "",
  );
  for (const [id, c] of Object.entries(ir.components)) {
    out.push(`## ${id}${note(id)}`, "");
    if (c.external) {
      out.push(t ? "The outside world (a stand-in in the tests)." : "外の世界（検証では代役）。");
      for (const [name, port] of Object.entries(c.external.queries)) {
        out.push(`- ${t ? "query" : "問い合わせ"} \`${name}(${Object.entries(port.params).map(([k, v]) => `${k}: ${typeText(v)}`).join(", ")}): ${typeText(port.result)}\`${port.promise ? ` (${port.promise})` : ""}${port.mayFail ? " (may fail)" : ""}`);
      }
      for (const [name, command] of Object.entries(c.external.commands)) out.push(`- ${t ? "command" : "コマンド"} \`${name}(${Object.entries(command.params).map(([k, v]) => `${k}: ${typeText(v)}`).join(", ")})\``);
      out.push("");
      continue;
    }
    if (c.contains?.length) out.push(`${t ? "Contains" : "中に持つ部品"}: ${c.contains.join(", ")}`);
    if (c.relies?.length) out.push(`${t ? "Relies on" : "外のもの"}: ${c.relies.join(", ")}`);
    if (c.durable) out.push(t ? "What it keeps survives a restart." : "覚えていることは、再起動を越えて残る。");
    if (Object.keys(c.state ?? {}).length) {
      out.push("", `### ${t ? "State" : "状態"}`, "");
      for (const [field, type] of Object.entries(c.state!)) out.push(`- \`${field}: ${typeText(type)}\` = ${r(c.init?.[field])}${note(`${id}.state.${field}`)}`);
    }
    for (const [name, command] of Object.entries(c.commands ?? {})) {
      out.push("", `### ${t ? "Command" : "コマンド"} \`${name}(${Object.entries(command.params).map(([k, v]) => `${k}: ${typeText(v)}`).join(", ")})\`${command.output ? `: ${typeText(command.output)}` : ""}${note(`${id}.commands.${name}`)}`, "");
      if (command.requires !== undefined) out.push(`${t ? "Only when" : "仕様の範囲"}: ${r(command.requires)}`, "");
      for (const eventName of command.events) {
        const event = c.events![eventName];
        out.push(`- **${eventName}** ${t ? "when" : "条件"}: ${r(event.guard)}`);
        for (const [field, value] of Object.entries(event.assign)) out.push(`  - this.${field} := ${r(value)}`);
        for (const call of event.calls) out.push(`  - ${t ? "call" : "呼ぶ"} ${call.component}.${call.command}(${Object.entries(call.args).map(([k, v]) => `${k}: ${r(v)}`).join(", ")})${call.when !== undefined ? ` ${t ? "if" : "ただし"} ${r(call.when)}` : ""}`);
        if (event.output !== undefined) out.push(`  - ${t ? "answers" : "答え"} ${r(event.output)}`);
      }
    }
    for (const [name, query] of Object.entries(c.queries ?? {})) {
      out.push("", `### ${t ? "Query" : "問い合わせ"} \`${name}(${Object.entries(query.params).map(([k, v]) => `${k}: ${typeText(v)}`).join(", ")}): ${typeText(query.result)}\`${note(`${id}.queries.${name}`)}`, "", `${t ? "Answers" : "答え"}: ${r(query.is)}`);
    }
    const named = [
      ...Object.entries(c.conditions ?? {}).map(([name, x]) => [`conditions.${name}`, `${name}(${Object.keys(x.params).join(", ")})`, x.is] as const),
      ...Object.entries(c.calcs ?? {}).map(([name, x]) => [`calcs.${name}`, `${name}(${Object.keys(x.params).join(", ")})`, x.is] as const),
    ];
    if (named.length) {
      out.push("", `### ${t ? "Named conditions and calculations" : "名前を付けた条件と計算"}`, "");
      for (const [path, head, is] of named) out.push(`- \`${head}\`${note(`${id}.${path}`)}: ${r(is)}`);
    }
    for (const [name, table] of Object.entries(c.decisions ?? {})) {
      out.push("", `### ${t ? "Decision table" : "決定表"} \`${name}(${Object.keys(table.params).join(", ")})\`${note(`${id}.decisions.${name}`)}`, "");
      table.rows.forEach((row, i) => out.push(`${i + 1}. ${row.when === true ? "otherwise" : r(row.when)} → ${Object.entries(row.then).map(([k, v]) => `${k}: ${r(v)}`).join(", ")}`));
    }
    if (Object.keys(c.properties ?? {}).length) {
      out.push("", `### ${t ? "Properties (they hold in the spec; rely on them)" : "性質"}`, "");
      for (const [name, property] of Object.entries(c.properties!)) out.push(`- ${name} (${property.kind})${note(`${id}.rules.${name}`)}: ${r(property.is)}`);
    }
    out.push("");
  }
  return `${out.join("\n").trimEnd()}\n`;
}
