type Target = { file: string; units: Unit[]; final: string; draft: string; current?: string };

function targetsOf(program: Program): Target[] {
  const byFile = new Map<string, Unit[]>();
  for (const unit of program.units) {
    if (unit.kind === "external" || INTERPRETATION_FILE.test(unit.file)) continue;
    if (!hasProse(unit)) continue;
    byFile.set(unit.file, [...(byFile.get(unit.file) ?? []), unit]);
  }
  // a file before the files that import it (a component is interpreted before the ones that use it)
  const order: string[] = [];
  const visit = (file: string, trail: string[] = []) => {
    if (order.includes(file) || trail.includes(file)) return;
    const module = program.modules.get(file);
    for (const imp of module?.imports ?? []) if (imp.from.startsWith(".")) visit(resolve(dirname(file), imp.from), [...trail, file]);
    order.push(file);
  };
  for (const file of [...byFile.keys()].sort()) visit(file);
  return order.filter((file) => byFile.has(file)).map((file) => [file, byFile.get(file)!] as const).map(([file, units]) => {
    const final = units.find((u) => u.interpretation && !u.interpretation.file.endsWith(DRAFT_SUFFIX))?.interpretation?.file ?? interpretationFileOf(file);
    const draft = final.replace(/\.ts$/, DRAFT_SUFFIX);
    const current = existsSync(draft) ? draft : existsSync(final) ? final : undefined;
    return { file, units, final, draft, ...(current ? { current } : {}) };
  });
}

