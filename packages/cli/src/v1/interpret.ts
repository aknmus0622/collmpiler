const typeText = (t: Type): string => {
  if (t === "int") return "Int";
  if (t === "string") return "string";
  if (t === "bool") return "boolean";
  if (t === "json") return "Json";
  if ("enum" in t) return t.enum.map((v) => JSON.stringify(v)).join(" | ");
  if ("atom" in t) return t.atom;
  if ("optional" in t) return `${typeText(t.optional)} | null`;
  if ("list" in t) return `${typeText(t.list)}[]`;
  if ("set" in t) return `SpecSet<${typeText(t.set)}>`;
  if ("map" in t) return `SpecMap<${typeText(t.map[0])}, ${typeText(t.map[1])}>`;
  return `{ ${Object.entries(t.record).map(([k, v]) => `${k}: ${typeText(v)}`).join("; ")} }`;
};

/** The places a body of Layer 1 left as prose: `is.x("…")` without an expression, `does.x("…")`, with the method they are in. */
function fragmentsOf(unit: Unit): { kind: "is" | "does" | "value"; name: string; text: string; where: string; params: string }[] {
  const found: { kind: "is" | "does" | "value"; name: string; text: string; where: string; params: string }[] = [];
  const paramsText = (params: { name: string; type?: unknown }[], module: Unit["module"]) =>
    params.map((p) => `${p.name}${p.type ? `: ${typeSource(p.type as never, module)}` : ""}`).join(", ");
  const walk = (node: unknown, where: string, params: string) => {
    if (typeof node !== "object" || node === null) return;
    if (Array.isArray(node)) return node.forEach((n) => walk(n, where, params));
    const n = node as Expr;
    if (n.k === "call" && n.callee.k === "member" && n.callee.object.k === "id" && ["is", "does", "value"].includes(n.callee.object.name)) {
      const kind = n.callee.object.name as "is" | "does" | "value";
      if (kind === "does" || n.args.length === 1) {
        const text = proseOf(n.args[0]) ?? "";
        found.push({ kind, name: n.callee.name, text, where, params });
      }
    }
    Object.values(n).forEach((v) => walk(v, where, params));
  };
  for (const entry of unit.entries.values()) {
    if (entry.layer !== 1 || !entry.method) continue;
    walk(entry.method.body, `${entry.heading}.${entry.name}`, paramsText(entry.method.params, unit.module));
  }
  if (unit.fn) walk(unit.fn.body, unit.exportName, paramsText(unit.fn.params, unit.module));
  return found;
}
function typeSource(node: import("./syntax.ts").TypeNode, module: Unit["module"]): string {
  void module;
  switch (node.k) {
    case "tref":
      return node.args.length ? `${node.name}<${node.args.map((a) => typeSource(a, module)).join(", ")}>` : node.name;
    case "tlit":
      return JSON.stringify(node.value);
    case "tkw":
      return node.name;
    case "tunion":
      return node.types.map((t) => typeSource(t, module)).join(" | ");
    case "tarray":
      return `${typeSource(node.of, module)}[]`;
    case "tobj":
      return `{ ${node.fields.map((f) => `${f.name}${f.optional ? "?" : ""}: ${typeSource(f.type, module)}`).join("; ")} }`;
    case "tfn":
      return "unknown";
  }
}

/** The draft to start from: what each unit left as prose, as TODO comments under the heading it belongs to. */
function skeleton(target: Target, specsDir: string, pinned?: Map<string, Ir8>): string {
  const imports = new Map<string, Set<string>>();
  const use = (file: string, name: string) => imports.set(file, new Set([...(imports.get(file) ?? []), name]));
  const blocks: string[] = [];
  for (const unit of target.units) {
    use(target.file, unit.exportName);
    const headings = new Map<string, string[]>();
    const add = (heading: string, line: string) => headings.set(heading, [...(headings.get(heading) ?? []), line]);
    if (unit.proseOnly) {
      add("state", `// TODO: what ${unit.exportName} remembers: name: Map<K, V>() / Set<T>() / List<T>() / init<T>(value)`);
      add("commands", "// TODO: what drives it (methods with typed parameters)");
      add("queries", "// TODO: what it answers about what it remembers");
      const ir = pinned?.get(unit.id);
      if (ir) {
        const c = ir.components[unit.id];
        for (const [name, command] of Object.entries(c.commands ?? {})) {
          add("commands", `${name}(${Object.entries(command.params).map(([p, t]) => `${p}: ${typeText(t)}`).join(", ")})${command.output ? `: ${typeText(command.output)}` : ""} {\n      // TODO\n    },`);
        }
        for (const [name, query] of Object.entries(c.queries ?? {})) {
          add("queries", `${name}(${Object.entries(query.params).map(([p, t]) => `${p}: ${typeText(t)}`).join(", ")}): ${typeText(query.result)} {\n      // TODO\n    },`);
        }
      }
    }
    for (const entry of unit.entries.values()) {
      if (entry.layer !== 1 || entry.prose === undefined) continue;
      const pinnedPort = pinned?.get(unit.id)?.components[unit.id];
      const signature = entry.heading === "commands" ? pinnedPort?.commands?.[entry.name] : entry.heading === "queries" ? pinnedPort?.queries?.[entry.name] : undefined;
      if (signature) {
        const params = Object.entries(signature.params).map(([p, t]) => `${p}: ${typeText(t)}`).join(", ");
        const output = "output" in signature && signature.output ? `: ${typeText(signature.output)}` : "result" in signature ? `: ${typeText(signature.result)}` : "";
        add(entry.heading, `// 「${entry.prose}」\n    ${entry.name}(${params})${output} {\n      // TODO\n    },`);
      } else add(entry.heading, `// TODO ${entry.name}: 「${entry.prose}」`);
    }
    for (const fragment of fragmentsOf(unit)) {
      add(fragment.kind === "is" ? "conditions" : fragment.kind === "value" ? "calcs" : "does", `// TODO ${fragment.name}(${fragment.params}): 「${fragment.text}」 (in ${fragment.where})${fragment.kind === "is" ? " — return a boolean expression" : fragment.kind === "value" ? " — return the value" : ""}`);
    }
    if (unit.proseOnly || (unit.description && [...unit.entries.values()].length === 0)) {
      add("trace", `// TODO: each sentence of the description, as "the sentence (or a part of it)": ["the names it became"]`);
    }
    const body = [...headings]
      .sort(([a], [b]) => [...HEADINGS, "trace"].indexOf(a as never) - [...HEADINGS, "trace"].indexOf(b as never))
      .map(([heading, lines]) => `  ${heading}: {\n${lines.map((line) => `    ${line}`).join("\n")}\n  },`)
      .join("\n");
    blocks.push(`export const ${unit.exportName}Interpretation = interpretation(${unit.exportName}, {\n${body}\n});`);
  }
  const importLines = [...imports].map(([file, names]) => `import { ${[...names].sort().join(", ")} } from "./${rel(dirname(target.final), file)}";`);
  void specsDir;
  return `import { after, always, does, init, interpretation, is, List, Map, requires, Set, value } from "@clp/core/v1";
import type { Id, Int, Json, SpecMap, SpecSet } from "@clp/core/v1";
${importLines.join("\n")}

${blocks.join("\n\n")}
`;
}

