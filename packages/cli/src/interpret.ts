// 解釈 (Layer 2) を LLM に導かせる。実装のループとは別の、仕様を書く人のための工程。
// 人が書くのは Layer 1 だけ。解釈は、Layer 1 が構造として書かなかった分 (構造) と、名前の意味 (関数) を持つ。
//
// 解釈は採点の正解なので、LLM が導いたものをそのまま正解にはしない:
//   - 解釈がまだ無ければ、雛形から書かせる。すでにあって、Layer 1 の変更で古くなっていれば、
//     いまの解釈を出発点にして、合わなくなった所だけを直させる。いまの Layer 1 に合っていれば、何もしない
//   - 導いたものは <名前>.interpretation.draft.ts に書き出す。ローダーは既定で *.draft.ts を読まないので、
//     人が確定する (accept) まで、検証には使われない
//   - 機械的に確かめられること（型エラー、Layer 1 の書き換え、参照の誤り、条件の衝突、不変条件、値の型）は、
//     書き出す前に検査して差し戻す
//   - sessions が 2 以上のときは、ほかのセッションにも、同じ境界のもとで独立に解釈させ、1つ目と同じコマンド列で実行して比べる。
//     食い違う所は、Layer 1 の記述があいまいな所である。人はそこを読んで、Layer 1 を詳しくする
// 記述と解釈が合っているかを最後に決めるのは、人である。

