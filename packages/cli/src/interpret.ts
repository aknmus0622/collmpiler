// Layer 1 に書かれたコマンド（文だけなら description だけを持つ）。コマンドが並べられていなければ undefined
function sketched(layer1: Layer1): Record<string, CommandShape> | undefined {
  const commands = layer1.commands;
  if (commands === undefined || isDescription(commands)) return undefined;
  return Object.fromEntries(
    Object.entries(commands).map(([name, part]) => [name, isDescription(part) ? { description: part.$description } : isFragment(part) ? part.$fragment : {}]),
  );
}

// Layer 1 に出てくる条件の文（決定表の行、onlyIf、when のキー）
function sentences(layer1: Layer1): string[] {
  const found = new Set<string>();
  for (const table of Object.values(layer1.decisions ?? {})) for (const row of Object.keys(table)) found.add(row);
  for (const shape of Object.values(sketched(layer1) ?? {})) {
    for (const name of [...(shape.onlyIf ?? []), ...Object.keys(shape.when ?? {})]) found.add(name);
  }
  found.delete("otherwise");
  return [...found].sort();
}

