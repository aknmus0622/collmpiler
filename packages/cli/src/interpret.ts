export const aspectLabel = (aspect: string) =>
  aspect === "runs" ? "実行できるかどうか" : aspect === "state" ? "遷移先" : aspect === "output" ? "返す値" : aspect === "order" ? "副作用の順序" : `副作用 ${aspect.slice("effect:".length)}`;

export const describeDifference = (difference: Difference, session: number) => {
  const path = difference.steps.map((step) => `${step.command} ${JSON.stringify({ ...step.input, ...step.queries })}`).join(" → ");
  return `${session} つ目の解釈と食い違う (${difference.command}、${aspectLabel(difference.aspect)}): ${path}。1つ目: ${JSON.stringify(difference.first)}、${session} つ目: ${JSON.stringify(difference.other)}`;
};

// 下書きの先頭（ハッシュの行のあと）に、食い違いを書き足す
function markComparisons(draft: string, comparisons: Comparison[]) {
  const lines = comparisons.flatMap((comparison) =>
    comparison.status === "failed"
      ? [`${CLP_REVIEW}${comparison.session} つ目の解釈を導けなかったので、比べていません（あいまいな所が見つかっていない可能性があります）`]
      : comparison.differences.map((difference) => CLP_REVIEW + describeDifference(difference, comparison.session)),
  );
  if (lines.length === 0) return;
  const text = withoutClpReviews(readFileSync(draft, "utf8"));
  const at = text.indexOf("\n", text.indexOf(STAMP)) + 1;
  writeFileSync(draft, text.slice(0, at) + lines.join("\n") + "\n" + text.slice(at));
}
