export function specHash(ir: Ir): string {
  return `sha256:${createHash("sha256").update(stableStringify(ir)).digest("hex")}`;
}

function header(ir: Ir): string {
  return `// Code generated by clp. DO NOT EDIT.\n// ir-version: ${ir.irVersion}\n// spec-hash:  ${specHash(ir)}\n`;
}

const union = (values: readonly string[]) => values.map((value) => JSON.stringify(value)).join(" | ") || "never";

function fieldType(schema: FieldSchema): string {
  if (isOptional(schema)) return `${fieldType(schema.optional)} | null`;
  if (isList(schema)) {
    const item = fieldType(schema.list);
    return /[ |]/.test(item) && !item.startsWith("{") ? `(${item})[]` : `${item}[]`;
  }
  if (isRecord(schema)) {
    const fields = Object.keys(schema.record).sort().map((field) => `${field}: ${fieldType(schema.record[field])}${schema.optional?.includes(field) ? " | null" : ""}`);
    return fields.length === 0 ? "{}" : `{ ${fields.join("; ")} }`;
  }
  if (isEnum(schema)) return union(schema);
  if (isStringSchema(schema)) return "string";
  if (isNumberSchema(schema) || schema === "integer") return "number";
  return schema as string;
}

function shape(fields: Record<string, FieldSchema>): string {
  const entries = Object.keys(fields).sort().map((key) => `${key}: ${fieldType(fields[key])}`);
  return entries.length === 0 ? "{}" : `{ ${entries.join("; ")} }`;
}

const members = (lines: string[]) => (lines.length === 0 ? "{}" : `{\n${lines.map((line) => `    ${line};`).join("\n")}\n  }`);

// アダプターの契約。エージェントが読むのでコメントは英語。
export function generateContract(ir: Ir): string {
  const model = requireModel(ir);
  const behaviors = [...ir.behaviors].sort((a, b) => (a.name < b.name ? -1 : 1));
  // 含む部品の依存も、部品の名前で修飾して並ぶ（todos.newId）。アダプターが、それを中の部品のコードに渡す
  const allQueries = { ...model.queries };
  const allEffects = { ...model.effects };
  for (const [part, boundary] of Object.entries(model.parts ?? {})) {
    for (const [name, query] of Object.entries(boundary.queries)) allQueries[`${part}.${name}`] = query;
    for (const [name, fields] of Object.entries(boundary.effects)) allEffects[`${part}.${name}`] = fields;
  }
  const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));
  const queries = Object.keys(allQueries).sort().map((name) => {
    const { input, output, promise } = allQueries[name];
    // 依存の約束。代役は、これを守って答える
    const note = promise === "fresh" ? "/** Never answers with the same value twice. */ " : promise === "increasing" ? "/** Never answers with less than it answered before. */ " : "";
    return `${note}${key(name)}(${Object.keys(input).length > 0 ? `input: ${shape(input)}` : ""}): ${fieldType(output)}`;
  });
  const effects = Object.keys(allEffects).sort().map((name) => `${key(name)}(payload: ${shape(allEffects[name])}): void`);
  // コマンドが返すもの。返すコマンドが無ければ、契約は以前のまま
  const outputs = Object.keys(model.outputs ?? {}).sort().map((name) => {
    return `${name}: ${fieldType(model.outputs![name])}`;
  });
  const results =
    outputs.length === 0
      ? ""
      : `/**
 * What a command answers with. Return it from \`executeCommand\`; it is compared with the specification.
 * A field typed \`| null\` is \`null\` when the command has no value for it. Commands not listed here answer nothing.
 */
export type CommandOutput = {
${outputs.map((line) => `  ${line};`).join("\n")}
};

`;

  // 経路: コマンドが外からどう届くか。HTTP の決まりは、契約の文で述べる（仕様は HTTP の意味を持たない）
  const routes = Object.keys(model.routes ?? {}).sort();
  const routing =
    routes.length === 0
      ? ""
      : `/**
 * The commands below reach the production system as HTTP requests. Start its server in \`setupIsolation\`
 * (on a free port) and send each command to its route:
 * - the method and the path are the route; a path segment \`:name\` is the input field \`name\` (URL-encoded);
 * - the input field \`body\` is the JSON request body; every other input field goes into the query string;
 * - the answer has the fields the command's output declares: \`status\` is the response status code, and
 *   \`body\` the response body parsed as JSON (\`null\` when the response has no body).
 */
export const routes = {
${routes.map((name) => `  ${name}: ${JSON.stringify(model.routes![name])},`).join("\n")}
} as const;

`;

  return `${header(ir)}
export type StateName = ${union(model.states)};

/** One command to execute: its name and the input that goes with it. */
export type Command =
${behaviors.map((b) => `  | { name: ${JSON.stringify(b.name)}; input: ${shape(model.commands[b.name] ?? {})} }`).join("\n")};

${routing}${results}/**
 * Stand-ins for everything the system depends on. The test harness owns them; connect them to
 * whatever seams your production code has.${
   Object.keys(model.parts ?? {}).length > 0
     ? "\n * A name with a dot (`todos.newId`) is a dependency of a component the system contains (`todos`): connect it to that component's code."
     : ""
 }
 */
export type Ports = {
  /**
   * Values the system asks its environment for (a clock, configuration, the response of an external service).
   * Answers can differ between commands: ask when needed, do not cache.
   * A query that takes an \`input\` is a question about that input. Pass on exactly what the production code
   * asked about; a question the specification does not ask in that command makes the test fail.
   */
  queries: ${members(queries)};
  /** Side effects the system performs on its environment. Calls are recorded in order and compared with the spec. */
  effects: ${members(effects)};
};

/** The test harness drives the production system only through this interface. */
export interface TargetSystemAdapter {
  /** Called before each trial. Build a fresh system in the initial state, connected to \`ports\`. */
  setupIsolation(ports: Ports): Promise<void>;
  /** Called after each trial, pass or fail. Discard everything the trial created. */
  teardownIsolation(): Promise<void>;
  /** Execute one command. A trial executes several commands in sequence on the same system. */
  executeCommand(command: Command): Promise<${outputs.length === 0 ? "void" : "CommandOutput[keyof CommandOutput] | void"}>;
  /** The current state of the system. */
  getCurrentState(): Promise<StateName>;
}
`;
}

// アダプターの雛形が出すエラー。本番コードの「未実装」とは別の文言にする。
// 同じだと、配線の段階が何も書かなくても「未実装で失敗した」ように見えて、赤の確認を通ってしまう
export const ADAPTER_NOT_WRITTEN = "the adapter is not written yet";

export function generateAdapterSkeleton(ws: Workspace): string {
  const methods = ["setupIsolation(ports)", "teardownIsolation()", "executeCommand(command)", "getCurrentState()"];
  return `import type { TargetSystemAdapter } from "${importPath(ws.paths.adapter, ws.paths.contract)}";

// Import the production code from ${dirFrom(ws.paths.adapter, ws.src)} and forward each call to it. No business logic here.
export const adapter: TargetSystemAdapter = {
${methods.map((method) => `  async ${method} {\n    throw new Error("${ADAPTER_NOT_WRITTEN}");\n  },`).join("\n")}
};
`;
}

export function generateVerify(ir: Ir, ws: Workspace, specsDir: string): string {
  const specs = relative(testsDirOf(ws), specsDir).split(sep).join("/");
  return `${header(ir)}
import { fileURLToPath } from "node:url";
import { runPbt } from "@clp/cli/runtime";
import { adapter } from "./${posix.basename(ws.paths.adapter)}";

await runPbt({ specs: fileURLToPath(new URL(${JSON.stringify(specs + "/")}, import.meta.url)), component: ${JSON.stringify(ws.component)}, adapter });
`;
}

// 検証のシード。仕様のハッシュから決める（検証を決定的にするため）
export const seedOf = (ir: Ir): number => Number.parseInt(specHash(ir).slice("sha256:".length, "sha256:".length + 7), 16);

export function requireModel(ir: Ir): IrModel {
  if (!ir.model) throw new Error("仕様にコンポーネントがありません（component(...) を export してください）");
  return ir.model;
}
